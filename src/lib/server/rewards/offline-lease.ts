import { createPrivateKey, sign } from 'node:crypto';
import { REWARD_UNITS, type RewardFeature } from './reward-engine';

export interface OfflineRewardLease {
  id: string;
  accountId: string;
  deviceId: string;
  feature: RewardFeature;
  units: number;
  sequence: number;
  issuedAt: number;
  expiresAt: number;
}
export const LEASE_MAX_AGE_MS = 7 * 24 * 60 * 60 * 1000;
const idPattern = /^[A-Za-z0-9_-]{16,128}$/;

/** The allocation store must commit the balance debit and lease row in one transaction.
 * Retry the same operation ID to recover a previously issued lease, never debit twice.
 */
export interface OfflineAllocationStore {
  allocate(accountId: string, deviceId: string, feature: RewardFeature, operationId: string): Promise<OfflineRewardLease | null>;
}

export function leasePayload(lease: OfflineRewardLease): string {
  if (![lease.id, lease.accountId, lease.deviceId].every(id => idPattern.test(id)) ||
      !Object.prototype.hasOwnProperty.call(REWARD_UNITS, lease.feature) ||
      !Number.isSafeInteger(lease.units) || lease.units < 1 || lease.units > REWARD_UNITS[lease.feature] ||
      !Number.isSafeInteger(lease.sequence) || lease.sequence < 1 ||
      !Number.isSafeInteger(lease.issuedAt) || lease.issuedAt < 1 ||
      !Number.isSafeInteger(lease.expiresAt) || lease.expiresAt <= lease.issuedAt ||
      lease.expiresAt - lease.issuedAt > LEASE_MAX_AGE_MS) throw new Error('invalid_reward_lease');
  return ['AU-REWARD-V1',lease.id,lease.accountId,lease.deviceId,lease.feature,
    lease.units,lease.sequence,lease.issuedAt,lease.expiresAt].join('\n');
}

/** Only server-owned P-256 keys. No key is embedded or generated by a client. */
export function signOfflineLease(lease: OfflineRewardLease, privatePem: string) {
  const key = createPrivateKey(privatePem);
  if (key.asymmetricKeyType !== 'ec' || key.asymmetricKeyDetails?.namedCurve !== 'prime256v1')
    throw new Error('invalid_reward_signing_key');
  const payload = leasePayload(lease);
  return {payload, signature:sign('sha256',Buffer.from(payload,'utf8'),key).toString('base64url')};
}
export async function issueOfflineLease(store: OfflineAllocationStore, accountId: string,
  deviceId: string, feature: RewardFeature, operationId: string, privatePem: string) {
  if (![accountId,deviceId,operationId].every(id => idPattern.test(id)) ||
      !Object.prototype.hasOwnProperty.call(REWARD_UNITS,feature)) throw new Error('invalid_allocation');
  // The caller must authenticate account ownership and prove the registered device key.
  const lease = await store.allocate(accountId,deviceId,feature,operationId);
  if (!lease) return null;
  if (lease.accountId !== accountId || lease.deviceId !== deviceId || lease.feature !== feature)
    throw new Error('allocation_scope_mismatch');
  return signOfflineLease(lease,privatePem);
}
